Fs=44.1e3;
t=0:1/Fs:1;
f=1e3;
A=sin(2*pi*f*t);
plot(A);
f1=10;
f2=20;
f3=30;
A1=sin(2*pi*f1*t);
A2=sin(2*pi*f2*t);
A3=sin(2*pi*f3*t);
